type RecipeNarrative = {
  chapters: RecipeNarrativeChapter[];
  sources: SourceLink[];
};

type SceneCopy = [title: string, body: string];

// Keep historical claims separate from our interpretation of this recipe's taste.
function narrative(origin: SceneCopy, culture: SceneCopy, taste: SceneCopy, sources: SourceLink[]): RecipeNarrative {
  return {
    chapters: [origin, culture, taste].map(([title, body], index) => ({
      section: ["음식의 유래", "시대와 문화", "맛과 식감"][index],
      kicker: ["01 / ORIGIN", "02 / CULTURE", "03 / TASTE"][index],
      title,
      body,
    })),
    sources,
  };
}

